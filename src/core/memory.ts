import * as path from "path";
import { RepoFacts } from "./analyzer";
import { lastTestRun, SessionView, SupervisorOutput } from "./supervisor";
import { Decision, Requirement, TestRun } from "./types";

/**
 * Project memory -> compact context handoff. Structured and bounded so it can be pasted into a
 * new Claude Code session without dumping whole histories.
 */

export interface HandoffInput {
  projectName: string;
  goal: string;
  preferences: string;
  facts: RepoFacts | null;
  requirements: Requirement[];
  decisions: Decision[];
  testRuns: TestRun[];
  out: SupervisorOutput;
  sessions: SessionView[];
  attemptedFixes: string[]; // normalized repeated errors, newest first
  now: number;
}

const ago = (now: number, ts: number): string => {
  const m = Math.round((now - ts) / 60000);
  if (m < 1) return "just now";
  if (m < 60) return `${m} min ago`;
  if (m < 48 * 60) return `${Math.round(m / 60)} h ago`;
  return `${Math.round(m / 1440)} d ago`;
};

export function buildHandoff(h: HandoffInput, maxChars = 6000): string {
  const L: string[] = [];
  L.push(`# Handoff: ${h.projectName}`);
  L.push(`_Generated by BuildPilot ${new Date(h.now).toISOString().slice(0, 16).replace("T", " ")}. Facts marked (verified) were observed; others are inferred._`);
  L.push("");
  if (h.goal.trim()) L.push(`**Goal:** ${h.goal.trim()}`);
  L.push(`**Stage:** ${h.out.stage.stage} (${h.out.stage.confidence}) · **Health:** ${h.out.health.label} · **Progress:** ${h.out.progress.label}`);
  L.push("");
  const reqs = h.requirements.filter((r) => r.status !== "dropped");
  if (reqs.length) {
    L.push("## Requirements");
    for (const r of reqs.slice(0, 15)) {
      const mark = r.status === "done" ? (r.evidence === "verified" ? "[x] (verified)" : "[x] (unverified)") : r.status === "in_progress" ? "[~]" : "[ ]";
      L.push(`- ${mark} ${r.title}${r.acceptance ? ` (done when: ${r.acceptance})` : ""}`);
    }
    L.push("");
  }
  const lastTest = lastTestRun(h.testRuns);
  L.push("## Current state");
  if (h.facts) L.push(`- Stack: ${[...h.facts.languages, ...h.facts.frameworks].join(", ") || "unknown"}; ${h.facts.sourceFileCount} source files, ${h.facts.testFileCount} test files`);
  L.push(`- Tests: ${lastTest ? `${lastTest.passed ? "PASSED" : "FAILED"} \`${lastTest.command}\` ${ago(h.now, lastTest.startedAt)} (verified)` : "not run (unknown)"}`);
  for (const i of h.out.issues.filter((x) => x.severity === "blocker" || x.severity === "high").slice(0, 6)) L.push(`- Problem: ${i.title}`);
  L.push("");
  const recent = h.sessions.filter((s) => h.now - s.lastEventAt < 3 * 86400_000).slice(0, 4);
  if (recent.length) {
    L.push("## Recent sessions");
    for (const s of recent) {
      L.push(`- ${s.id.slice(0, 8)} · ${s.displayStatus} · ${ago(h.now, s.lastEventAt)}${s.currentTask ? ` · last task: "${s.currentTask.slice(0, 140)}"` : ""}`);
      if (s.editedFiles.length) L.push(`  - edited: ${s.editedFiles.slice(-8).map((f) => path.basename(f)).join(", ")}`);
      if (s.lastError) L.push(`  - last error: ${s.lastError.split("\n")[0]!.slice(0, 160)}`);
    }
    L.push("");
  }
  if (h.attemptedFixes.length) {
    L.push("## Already tried (don't repeat blindly)");
    for (const a of h.attemptedFixes.slice(0, 5)) L.push(`- Repeated error: ${a.slice(0, 160)}`);
    L.push("");
  }
  if (h.decisions.length) {
    L.push("## Decisions");
    for (const d of h.decisions.slice(0, 8)) L.push(`- ${d.title}${d.detail ? `: ${d.detail.slice(0, 160)}` : ""}`);
    L.push("");
  }
  if (h.preferences.trim()) {
    L.push("## Preferences");
    L.push(h.preferences.trim().slice(0, 600));
    L.push("");
  }
  L.push("## Next step");
  L.push(h.out.next ? `${h.out.next.title}. ${h.out.next.why}` : "No outstanding recommendation. Confirm the goal with the user.");
  let text = L.join("\n");
  if (text.length > maxChars) text = text.slice(0, maxChars - 20) + "\n…(truncated)";
  return text;
}

export function buildClaudeMd(f: RepoFacts, goal: string, decisions: Decision[], preferences: string): string {
  const pm = f.packageManager === "pnpm" ? "pnpm" : f.packageManager === "yarn" ? "yarn" : f.packageManager === "bun" ? "bun run" : "npm run";
  const L: string[] = [`# ${f.name}`, ""];
  if (goal.trim()) L.push(goal.trim(), "");
  else if (f.description) L.push(f.description, "");
  L.push("## Stack", [...f.languages, ...f.frameworks].join(", ") || "(fill in)", "");
  const cmds = Object.keys(f.scripts).filter((s) => ["dev", "start", "build", "test", "lint", "typecheck", "format"].includes(s));
  if (cmds.length) {
    L.push("## Commands");
    for (const c of cmds) L.push(`- \`${pm} ${c}\``);
    L.push("");
  }
  L.push("## Rules");
  L.push("- Run tests (and typecheck/lint if present) before saying a task is done; report the actual results.");
  L.push("- Keep changes small and focused; don't rewrite working code.");
  L.push("- Never commit secrets; config goes in .env (documented in .env.example).");
  L.push("- Ask before destructive operations (deleting files/data, force-push, resets).");
  if (preferences.trim()) L.push(`- ${preferences.trim().replace(/\n+/g, "\n- ")}`);
  if (decisions.length) {
    L.push("", "## Decisions");
    for (const d of decisions.slice(0, 10)) L.push(`- ${d.title}${d.detail ? `: ${d.detail}` : ""}`);
  }
  return L.join("\n") + "\n";
}
